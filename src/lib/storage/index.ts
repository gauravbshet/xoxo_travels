import "server-only";
import { createHmac, timingSafeEqual } from "node:crypto";
import { mkdir, open, rm, stat } from "node:fs/promises";
import path from "node:path";
import { AwsClient } from "aws4fetch";

/* File storage behind one small API.
   - "r2":    Cloudflare R2 (any S3-compatible store). Browser uploads straight to
              the bucket with a short-lived presigned PUT; the server never proxies files.
   - "local": development only, when R2 keys are missing. Files go to ./.uploads and
              are served by /api/media routes with HMAC-signed links.
   In production without keys, storageMode() throws. */

export type Bucket = "public" | "private";

const real = (v: string | undefined) => (v && v.trim() && !/x{6,}|<account-id>/i.test(v) ? v.trim() : undefined);
const cfg = () => ({
  endpoint: real(process.env.S3_ENDPOINT),
  region: real(process.env.S3_REGION) ?? "auto",
  accessKeyId: real(process.env.S3_ACCESS_KEY_ID),
  secretAccessKey: real(process.env.S3_SECRET_ACCESS_KEY),
  public: real(process.env.S3_BUCKET_PUBLIC),
  private: real(process.env.S3_BUCKET_PRIVATE),
  mediaBase: real(process.env.NEXT_PUBLIC_MEDIA_BASE_URL),
});

export function storageMode(): "r2" | "local" {
  const c = cfg();
  if (c.endpoint && c.accessKeyId && c.secretAccessKey && c.public && c.private && c.mediaBase) return "r2";
  if (process.env.NODE_ENV === "production") throw new Error("File storage is not configured. Set the S3_* variables and NEXT_PUBLIC_MEDIA_BASE_URL.");
  return "local";
}

/** Object keys are generated by the server; this also guards the local file paths. */
export const KEY_RE = /^(avatars|ids|chat)\/[a-z0-9]+\/[a-z0-9]+\.(jpg|png|webp|pdf)$/;

/* ───────── R2 ───────── */

function r2() {
  const c = cfg();
  return { client: new AwsClient({ accessKeyId: c.accessKeyId!, secretAccessKey: c.secretAccessKey!, service: "s3", region: c.region }), c };
}
const objectUrl = (bucket: Bucket, key: string) => {
  const c = cfg();
  return `${c.endpoint!.replace(/\/$/, "")}/${bucket === "public" ? c.public : c.private}/${key}`;
};
async function presign(method: "PUT" | "GET", bucket: Bucket, key: string, ttl: number, contentType?: string) {
  const { client } = r2();
  const url = new URL(objectUrl(bucket, key));
  url.searchParams.set("X-Amz-Expires", String(ttl));
  const signed = await client.sign(url.toString(), {
    method,
    ...(contentType && { headers: { "Content-Type": contentType } }),
    aws: { signQuery: true, allHeaders: Boolean(contentType) },
  });
  return signed.url;
}

/* ───────── local (dev) ───────── */

const ROOT = path.join(process.cwd(), ".uploads");
const localPath = (bucket: Bucket, key: string) => {
  if (!KEY_RE.test(key)) throw new Error("Bad storage key.");
  return path.join(ROOT, bucket, ...key.split("/"));
};
const localSecret = () => process.env.LOCAL_UPLOAD_SECRET || "dev-only-local-upload-secret";
const sign = (payload: string) => createHmac("sha256", localSecret()).update(payload).digest("hex");
export function verifyLocalSig(payload: string, sig: string) {
  const a = Buffer.from(sign(payload)), b = Buffer.from(sig);
  return a.length === b.length && timingSafeEqual(a, b);
}
export const localUploadPayload = (bucket: string, key: string, type: string, max: string, exp: string) => `put|${bucket}|${key}|${type}|${max}|${exp}`;
export const localViewPayload = (key: string, exp: string) => `get|private|${key}|${exp}`;
export { localPath };

/* ───────── API ───────── */

export type UploadTicket = { url: string; method: "PUT"; headers: Record<string, string>; key: string };

/** A short-lived URL the browser PUTs the file to. Size is re-checked after upload. */
export async function createUpload(bucket: Bucket, key: string, contentType: string, maxBytes: number, ttl: number): Promise<UploadTicket> {
  if (!KEY_RE.test(key)) throw new Error("Bad storage key.");
  if (storageMode() === "r2") return { url: await presign("PUT", bucket, key, ttl, contentType), method: "PUT", headers: { "Content-Type": contentType }, key };
  const exp = String(Math.floor(Date.now() / 1000) + ttl);
  const q = new URLSearchParams({ bucket, key, type: contentType, max: String(maxBytes), exp });
  q.set("sig", sign(localUploadPayload(bucket, key, contentType, String(maxBytes), exp)));
  return { url: `/api/uploads/local?${q}`, method: "PUT", headers: { "Content-Type": contentType }, key };
}

/** Size and the first bytes (for a magic-number check), or null if the object is missing. */
export async function inspect(bucket: Bucket, key: string, prefixBytes = 16): Promise<{ size: number; prefix: Uint8Array } | null> {
  if (storageMode() === "r2") {
    const { client } = r2();
    const res = await client.fetch(objectUrl(bucket, key), { method: "GET", headers: { Range: `bytes=0-${prefixBytes - 1}` } });
    if (res.status === 404) return null;
    if (!res.ok) throw new Error(`Storage read failed (${res.status}).`);
    const total = Number(res.headers.get("content-range")?.split("/")[1] ?? res.headers.get("content-length"));
    return { size: total, prefix: new Uint8Array(await res.arrayBuffer()).slice(0, prefixBytes) };
  }
  try {
    const p = localPath(bucket, key);
    const { size } = await stat(p);
    const fh = await open(p, "r");
    try { const buf = Buffer.alloc(prefixBytes); await fh.read(buf, 0, prefixBytes, 0); return { size, prefix: new Uint8Array(buf) }; }
    finally { await fh.close(); }
  } catch { return null; }
}

export async function removeObject(bucket: Bucket, key: string) {
  if (!key) return;
  if (storageMode() === "r2") {
    const { client } = r2();
    const res = await client.fetch(objectUrl(bucket, key), { method: "DELETE" });
    if (!res.ok && res.status !== 404) throw new Error(`Storage delete failed (${res.status}).`);
    return;
  }
  await rm(localPath(bucket, key), { force: true });
}

/** Public URL for a public-bucket object (profile photos). */
export function publicUrl(key: string) {
  return storageMode() === "r2" ? `${cfg().mediaBase!.replace(/\/$/, "")}/${key}` : `/api/media/${key}`;
}

/** Short-lived link to a private object (ID documents, admin only). */
export async function privateViewUrl(key: string, ttl: number) {
  if (storageMode() === "r2") return presign("GET", "private", key, ttl);
  const exp = String(Math.floor(Date.now() / 1000) + ttl);
  return `/api/media-private/${key}?exp=${exp}&sig=${sign(localViewPayload(key, exp))}`;
}

export async function ensureLocalDir(bucket: Bucket, key: string) {
  await mkdir(path.dirname(localPath(bucket, key)), { recursive: true });
}

/** Checks the real file type from its first bytes, not the name or declared type. */
export function sniff(prefix: Uint8Array): string | null {
  const b = prefix;
  if (b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "image/jpeg";
  if (b[0] === 0x89 && b[1] === 0x50 && b[2] === 0x4e && b[3] === 0x47) return "image/png";
  if (b[0] === 0x52 && b[1] === 0x49 && b[2] === 0x46 && b[3] === 0x46 && b[8] === 0x57 && b[9] === 0x45 && b[10] === 0x42 && b[11] === 0x50) return "image/webp";
  if (b[0] === 0x25 && b[1] === 0x50 && b[2] === 0x44 && b[3] === 0x46) return "application/pdf";
  return null;
}

export const extFor: Record<string, "jpg" | "png" | "webp" | "pdf"> = { "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp", "application/pdf": "pdf" };
